// Refreshes lib/auth/disposableDomains.ts from the public-domain (CC0) list at
// https://github.com/disposable-email-domains/disposable-email-domains.
// Run with: node scripts/update-disposable-domains.mjs
import { writeFile } from "node:fs/promises";

const BASE = "https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main";

async function fetchList(file) {
  const res = await fetch(`${BASE}/${file}`);
  if (!res.ok) throw new Error(`${file}: HTTP ${res.status}`);
  return (await res.text())
    .split("\n")
    .map((line) => line.trim().toLowerCase())
    .filter((line) => line && !line.startsWith("#"));
}

const domains = [...new Set(await fetchList("disposable_email_blocklist.conf"))].sort();

const out = `// Generated by scripts/update-disposable-domains.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
// Source: github.com/disposable-email-domains/disposable-email-domains (CC0 1.0).
// ${domains.length} domains, newline-separated.
export const DISPOSABLE_DOMAINS = \`
${domains.join("\n")}
\`;
`;
await writeFile(new URL("../lib/auth/disposableDomains.ts", import.meta.url), out);
console.log(`Wrote ${domains.length} domains.`);
